// Local dev chain: deploys MockUSDC + KillSwitchVault to anvil and writes .env.local.
//   anvil &              (in another terminal)
//   npm run local        -> writes .env.local
//   ENV_FILE=.env.local npm run setup && ENV_FILE=.env.local npm start
import fs from 'node:fs';
import path from 'node:path';
import { createPublicClient, createWalletClient, http } from 'viem';
import { privateKeyToAccount } from 'viem/accounts';
import { foundry } from 'viem/chains';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rpc = process.env.LOCAL_RPC || 'http://127.0.0.1:8545';
// anvil's well-known dev keys (never use these anywhere real)
const KEYS = {
  owner: '0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80',
  agent: '0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d',
  cloudtool: '0x5de4111afa1a4b94908f83103eb1f1706367c2e68ca870fc3fb9a804cdab365a',
  weather: '0x7c852118294e51e653712a81e05800f419141751be58f605c371e15141b007a6',
};
const load = (n) => JSON.parse(fs.readFileSync(path.join(ROOT, 'abi', `${n}.json`), 'utf8'));
const pub = createPublicClient({ chain: foundry, transport: http(rpc) });
const owner = createWalletClient({ account: privateKeyToAccount(KEYS.owner), chain: foundry, transport: http(rpc) });
const addr = (k) => privateKeyToAccount(KEYS[k]).address;

async function deploy(name, args = []) {
  const { abi, bytecode } = load(name);
  const hash = await owner.deployContract({ abi, bytecode, args });
  const r = await pub.waitForTransactionReceipt({ hash });
  return { address: r.contractAddress, abi };
}

const usdc = await deploy('MockUSDC');
const vault = await deploy('KillSwitchVault', [usdc.address, addr('owner'), addr('agent'), 5_000_000n]);
// Give the owner 100 mock USDC to fund the vault with during `npm run setup`.
await pub.waitForTransactionReceipt({ hash: await owner.writeContract({ ...usdc, functionName: 'mint', args: [addr('owner'), 100_000_000n] }) });

const env = `# generated by npm run local (anvil)
CHAIN_NAME=Anvil (local)
CHAIN_ID=31337
ARC_RPC_URL=${rpc}
EXPLORER_URL=http://localhost:8787/#local
USDC_ADDRESS=${usdc.address}
VAULT_ADDRESS=${vault.address}
OWNER_PRIVATE_KEY=${KEYS.owner}
AGENT_PRIVATE_KEY=${KEYS.agent}
MERCHANT_CLOUDTOOL_KEY=${KEYS.cloudtool}
MERCHANT_WEATHER_KEY=${KEYS.weather}
LOCAL_CHAIN=true
`;
const extra = fs.existsSync(path.join(ROOT, '.env')) ? fs.readFileSync(path.join(ROOT, '.env'), 'utf8').split('\n').filter((l) => /^(ELEVENLABS|QN_|PUBLIC_URL)/.test(l)).join('\n') : '';
fs.writeFileSync(path.join(ROOT, '.env.local'), env + extra + '\n');
console.log(`MockUSDC        ${usdc.address}\nKillSwitchVault ${vault.address}\nWrote .env.local`);
